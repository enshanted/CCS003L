#include <iostream>
using namespace std;

int main() {
    int num = 10;
    char letter = 'a';
    bool result = true;
    float float_val = 3.14;

    cout << "Number: " << num << endl;
    cout << "Letter: " << letter << endl;
    cout << "Result: " << (result ? "true" : "false") << endl;
    cout << "Float: " << float_val << endl;

    return 0;
}